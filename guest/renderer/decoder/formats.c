enum pipe_format
vr_format_from_virgl(uint32_t format)
{
   return format < ARRAY_SIZE(from_virgl) ? (enum pipe_format)from_virgl[format] : PIPE_FORMAT_NONE;
}

/* virgl's format as `dev` keeps it. OpenGL hosts take 24-bit depth with
 * stencil (or nothing) in the low byte of each texel, as
 * GL_UNSIGNED_INT_24_8 packs it, and clients ask for that (vgl's
 * GL_DEPTH24_STENCIL8 is S8_UINT_Z24_UNORM). A driver with depth only in
 * the lower 24 bits (iris) keeps those formats that way round: depth reads,
 * tests and clears the same, and transfers rotate each texel
 * (vr_rotate_depth). */
enum pipe_format
vr_format(const struct vr_device *dev, uint32_t format)
{
   enum pipe_format f = vr_format_from_virgl(format);
   if (dev->depth_low && f == PIPE_FORMAT_S8_UINT_Z24_UNORM)
      return PIPE_FORMAT_Z24_UNORM_S8_UINT;
   if (dev->depth_low && f == PIPE_FORMAT_X8Z24_UNORM)
      return PIPE_FORMAT_Z24X8_UNORM;
   return f;
}

/* Whether `dev` keeps virgl's format the other way round from the
 * client's texels. */
bool
vr_format_rotated(const struct vr_device *dev, uint32_t format)
{
   return vr_format(dev, format) != vr_format_from_virgl(format);
}

/* Rotates the 32-bit texels of `layers` layers of `rows` rows of `row`
 * bytes each (`stride` and `layer_stride` apart): depth from the upper 24
 * bits to the lower (`to_low`, the client's to the driver's), or back. */
void
vr_rotate_depth(uint8_t *mem, unsigned layers, uint64_t rows, uint64_t row, uint64_t stride, uint64_t layer_stride,
                bool to_low)
{
   for (unsigned z = 0; z < layers; z++) {
      for (uint64_t y = 0; y < rows; y++) {
         uint8_t *p = mem + z * layer_stride + y * stride;
         for (uint64_t x = 0; x + 4 <= row; x += 4) {
            uint32_t v;
            memcpy(&v, p + x, 4);
            v = to_low ? (v >> 8) | (v << 24) : (v << 8) | (v >> 24);
            memcpy(p + x, &v, 4);
         }
      }
   }
}
